test("Coordinator archives the active OOD count and keeps History private and read-only", async (t) => {
  const dom = new JSDOM('<div id="app"></div>', { url: "https://example.test/lush-inventory/", pretendToBeVisual: true });
  globalThis.window = dom.window; globalThis.document = dom.window.document; globalThis.XLSX = XLSX;
  window.confirm = () => true;
  t.after(() => { lockCoordinator(); dom.window.close(); });
  const root = document.getElementById("app");
  const source = importInventory(await readFile(new URL("./fixtures/PreChanges.xlsx", import.meta.url)), "OOD Weekly.xlsx");
  let active = createOODCount({ ...source, areaLabel: "Skincare and Mouth" }, "2026-10-14", 8);
  active = updateOODRow(active, active.products[0].id, "later", "7");
  await saveActiveCount(active);
  mountCoordinator(root, { getActiveCount: () => active, saveActiveCount: (next) => { active = next; }, onExit: () => {}, toast: () => {} });
  const unlock = async () => {
    root.querySelector('[name="pin"]').value = OWNER_PIN;
    root.querySelector("#pinForm").dispatchEvent(new window.Event("submit", { bubbles: true, cancelable: true }));
    await waitFor(() => root.querySelector("#archiveCurrent"));
  };
  await unlock();
  root.querySelector("#archiveCurrent").click();
  await waitFor(() => root.querySelector("[data-ood-archive]"));
  assert.deepEqual([...root.querySelectorAll("[data-tab]")].map((button) => button.textContent), ["Overview", "History"]);
  assert.equal(root.querySelector("#historyMode").value, "ood");
  assert.equal(root.querySelector("[data-archive]"), null);
  const filter = root.querySelector("#historyMode");
  filter.value = ""; filter.dispatchEvent(new window.Event("change"));
  assert.ok(root.querySelector("[data-archive]"));
  assert.match(root.querySelector("[data-ood-archive]").textContent, /^OOD Count - Area Skincare and Mouth - /);
  root.querySelector("[data-ood-archive]").click();
  assert.match(root.textContent, /OOD Weekly.xlsx/);
  assert.match(root.textContent, /Variance −1|Variance -1/);
  assert.equal(root.querySelectorAll("[data-bucket]").length, 0);
  assert.ok(root.querySelector("#exportOOD"));
  assert.match(root.textContent, /14 Feb 2026 or earlier/);
  const stored = await loadActiveCount();
  assert.ok(stored.archivedAt);
  assert.equal(stored.products[0].buckets.later, "7");
  lockCoordinator();
  assert.doesNotMatch(root.textContent, /OOD Weekly/);
});

test("the previous encrypted OOD draft is only recoverable into an empty active slot", async (t) => {
  const dom = new JSDOM('<div id="app"></div>', { url: "https://example.test/lush-inventory/", pretendToBeVisual: true });
  globalThis.window = dom.window; globalThis.document = dom.window.document; globalThis.XLSX = XLSX;
  window.confirm = () => true;
  t.after(() => { lockCoordinator(); dom.window.close(); });
  const source = importInventory(await readFile(new URL("./fixtures/PreChanges.xlsx", import.meta.url)), "Legacy OOD.xlsx");
  const draft = createOODCount(source, "2026-10-14", 7);
  const previous = await unlockVault(OWNER_PIN);
  await saveVault({ ...previous, oodDraft: draft });
  let active = await loadActiveCount(), exited = false;
  const root = document.getElementById("app");
  const callbacks = { getActiveCount: () => active, saveActiveCount: (next) => { active = next; }, onExit: () => { exited = true; }, toast: () => {} };
  const unlock = async () => {
    mountCoordinator(root, callbacks);
    const field = root.querySelector('[name="pin"]');
    field.value = OWNER_PIN; field.form.dispatchEvent(new window.Event("submit", { cancelable: true }));
    await waitFor(() => root.querySelector("#archiveLegacyOOD"));
  };
  await unlock();
  assert.equal(root.querySelector("#recoverLegacyOOD"), null);
  await clearActiveCount(); active = null;
  await unlock();
  root.querySelector("#recoverLegacyOOD").click();
  await waitFor(() => exited);
  assert.equal((await loadActiveCount()).id, draft.id);
  assert.equal((await unlockVault(OWNER_PIN)).oodDraft, null);
});
